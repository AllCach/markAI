    private static void expect(String action, String... messages) {
        for (String message : messages) {
            String actual = DialogueIntent.requestedAction(message);
            if (!actual.equals(action)) throw new AssertionError("Message " + message + ": expected " + action + ", got " + actual);
            checks++;
        }
    }
